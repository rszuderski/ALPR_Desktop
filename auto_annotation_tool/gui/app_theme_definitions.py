def normalize_theme_palette(palette: dict | None = None) -> dict:
    """Return a complete palette following the central application contract."""
    normalized = dict(THEME_PALETTE_CONTRACT)
    if isinstance(palette, dict):
        normalized.update({str(key): value for key, value in palette.items()})
        if "danger" not in palette:
            normalized["danger"] = normalized["error"]
    return normalized


def normalize_theme_definitions(themes: dict | None = None) -> dict:
    """Normalize every theme so runtime code never needs local color fallbacks."""
    normalized = {}
    for key, definition in (themes or {}).items():
        theme_key = str(key)
        theme_definition = dict(definition or {})
        theme_definition["label"] = str(theme_definition.get("label") or theme_key)
        theme_definition["palette"] = normalize_theme_palette(theme_definition.get("palette"))
        normalized[theme_key] = theme_definition
    return normalized


def get_theme_definition(theme_key: str | None = None, themes: dict | None = None) -> dict:
    """Resolve a theme definition from the central theme registry."""
    registry = themes or THEME_DEFINITIONS
    key = str(theme_key or DEFAULT_THEME_KEY)
    if key not in registry:
        key = DEFAULT_THEME_KEY
    return registry[key]


def get_theme_palette(theme_key: str | None = None, themes: dict | None = None) -> dict:
    """Resolve a fresh, complete palette for the requested theme."""
    return normalize_theme_palette(get_theme_definition(theme_key, themes).get("palette"))


def get_runtime_palette(owner=None) -> dict:
    """Resolve a normalized palette from app/tab/dialog owners."""
    candidate = owner
    for _ in range(4):
        if candidate is None:
            break
        palette = getattr(candidate, "palette", None)
        if isinstance(palette, dict):
            return normalize_theme_palette(palette)
        candidate = getattr(candidate, "app", None)
    return get_theme_palette(DEFAULT_THEME_KEY)


